// The icon that fits a treatment, from words in its name (and description)
const SERVICE_ICONS: [RegExp, (p: Props) => ReactNode][] = [
  [/deport|running|corred|atleta/, DumbbellIcon],
  [/embaraz|posparto|parto|infant|pediatr|bebe|nino/, BabyIcon],
  [/suelo pelv|pelvi|uroginec|hipopres/, HeartPulseIcon],
  [/pilates|ejercicio|yoga|grupo|clase|readapt|movimiento/, PersonIcon],
  [/puncion|aguja|acupun|epi\b|electrolisis/, NeedleIcon],
  [/masaj|manual|osteop|quiro|miofasc|drenaje|liberac/, HandIcon],
  [/respirat|pulmon/, WindIcon],
  [/pie|podo|plantill|tobillo/, FootprintsIcon],
  [/electro|ondas|tecar|laser|ultrason|magnet|indiba/, ZapIcon],
  [/valoraci|evaluaci|diagnost|primera|revision/, ClipboardIcon],
  [/espalda|columna|cervical|lumbar|trauma|postural|articul|hueso|fractura/, BoneIcon],
];

export function ServiceIcon({ name, description, className }: { name: string; description?: string } & Props) {
  const text = `${name} ${description ?? ""}`
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
  // The name decides first; the description only when the name says nothing
  const pick = (t: string) => SERVICE_ICONS.find(([re]) => re.test(t))?.[1];
  const Icon = pick(name.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "")) ?? pick(text) ?? ActivityIcon;
  return <>{Icon({ className })}</>;
}
